typedef enum WCS_PROFILE_MANAGEMENT_SCOPE {
    WCS_PROFILE_MANAGEMENT_SCOPE_SYSTEM_WIDE = 0,
    WCS_PROFILE_MANAGEMENT_SCOPE_CURRENT_USER = 1
} WCS_PROFILE_MANAGEMENT_SCOPE;

typedef enum COLORPROFILETYPE {
    CPT_ICC = 0, CPT_DMP = 1, CPT_CAMP = 2, CPT_GMMP = 3
} COLORPROFILETYPE;

typedef enum COLORPROFILESUBTYPE {
    CPST_PERCEPTUAL = 0, CPST_RELATIVE_COLORIMETRIC = 1, CPST_SATURATION = 2,
    CPST_ABSOLUTE_COLORIMETRIC = 3, CPST_NONE = 4, CPST_RGB_WORKING_SPACE = 5,
    CPST_CUSTOM_WORKING_SPACE = 6, CPST_STANDARD_DISPLAY_COLOR_MODE = 7,
    CPST_EXTENDED_DISPLAY_COLOR_MODE = 8
} COLORPROFILESUBTYPE;

// Real mscms signatures (Win10 2004+). Displays are addressed by
