// mhc2_filter.exe — full-desktop grayscale via MHC2 ICC display profile
//
// Applies a color matrix at the kernel/scanout level (the same pipeline
// Windows' built-in color filter uses), so there is NO capture, NO overlay
// window, and ~zero per-frame cost.
//
// Control file: %SYSTEMROOT%\Temp\mhc2_filter_mode.txt   (0=off, 1=luma, 2=oklch)
// State  file: %SYSTEMROOT%\Temp\mhc2_filter_state.txt  (monitorDevicePath|origProfile per line)
// Log    file: %SYSTEMROOT%\Temp\mhc2_filter.log
// ICC files : %LOCALAPPDATA%\Colorink\mhc2\{luma,oklch}.icc
//
// Requirements: Windows 10 2004+ and a GPU that supports the color-space
// transform DDI (Intel 10th gen iGPU+ / AMD RX 500+ / NVIDIA GTX 10xx+).
//
// Build: run build.bat

